"""Create a self-contained Overleaf ZIP from the verified English report."""
from __future__ import annotations

import re
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPORT = ROOT / "report"
OUTPUT = REPORT / "IMP302_Overleaf.zip"

main = (REPORT / "main.tex").read_text(encoding="utf-8")
old_path = r"\graphicspath{{../results/}{../notebooks/figures/}}"
assert old_path in main, "Unexpected graphics path; review source before packaging"
main = main.replace(old_path, r"\graphicspath{{figures/}}")
figure_names = re.findall(r"\\includegraphics(?:\[[^]]*\])?\{([^}]+)\}", main)
assert len(figure_names) == 4 and len(set(figure_names)) == 4

figure_paths = []
for name in figure_names:
    choices = [ROOT / "results" / name, ROOT / "notebooks/figures" / name]
    found = [p for p in choices if p.is_file()]
    assert len(found) == 1, f"Missing or ambiguous figure: {name}"
    figure_paths.append(found[0])

with zipfile.ZipFile(OUTPUT, "w", compression=zipfile.ZIP_DEFLATED) as archive:
    archive.writestr("main.tex", main)
    archive.write(REPORT / "results.tex", "results.tex")
    for path in figure_paths:
        archive.write(path, f"figures/{path.name}")
    archive.writestr(
        "README.txt",
        "IMP302 English research report\n"
        "Main document: main.tex\nCompiler: XeLaTeX\n"
        "Tables were generated by report/make_results.py from project results.\n",
    )

with zipfile.ZipFile(OUTPUT) as archive:
    assert archive.testzip() is None
    expected = {"main.tex", "results.tex", "README.txt"} | {f"figures/{n}" for n in figure_names}
    assert set(archive.namelist()) == expected
    assert all(not n.startswith("/") and ".." not in Path(n).parts for n in archive.namelist())
print(f"Created {OUTPUT} ({OUTPUT.stat().st_size:,} bytes; {len(expected)} files)")
